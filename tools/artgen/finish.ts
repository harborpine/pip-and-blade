/** After the SVGs: the PNG app icons (rasterised from app.icon) and the gallery page. */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { SpriteInfo } from '../../src/shared/assets';
import { ASSET_LIST } from '../../src/shared/assets';
import { writeAppIcons } from './appicon';
import { c } from './palette';

export function galleryHtml(manifest: Record<string, SpriteInfo>): string {
  const names = new Map(ASSET_LIST.map((a) => [a.id, a.name]));
  const cats = [...new Set(Object.keys(manifest).map((id) => id.split('.')[0]!))];
  const tile = (id: string, s: SpriteInfo): string => {
    const big = s.w >= 300;
    const style = big ? 'width:120px;height:auto' : `width:${s.w === 24 ? 48 : 64}px;height:auto`;
    return `<figure><div class="pair"><div class="light"><img src="${s.file}" alt="" style="${style}"></div><div class="dark"><img src="${s.file}" alt="" style="${style}"></div></div><figcaption><b>${names.get(id) ?? id}</b><br><code>${id}</code></figcaption></figure>`;
  };
  const sections = cats.map((cat) => {
    const ids = Object.keys(manifest).filter((id) => id.startsWith(`${cat}.`)).sort();
    return `<h2>${cat} (${ids.length})</h2><div class="grid">${ids.map((id) => tile(id, manifest[id]!)).join('')}</div>`;
  }).join('\n');
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Pip &amp; Blade art gallery</title>
<style>
body{margin:0;padding:16px;background:${c('paper')};color:${c('ink')};font-family:ui-rounded,'SF Pro Rounded',system-ui,sans-serif}
h1{font-size:24px;font-weight:800}h2{font-size:18px;font-weight:800;margin-top:28px}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(150px,1fr));gap:12px}
figure{margin:0;background:#fff0;border:1px solid ${c('ivory-dim')};border-radius:14px;overflow:hidden}
.pair{display:flex}.pair>div{flex:1;display:flex;align-items:center;justify-content:center;padding:10px;min-height:72px}
.light{background:${c('paper')};color:${c('ink')}}.dark{background:${c('slate')};color:${c('ivory')}}
figcaption{padding:6px 8px;font-size:12px;line-height:1.3}code{color:${c('ink-soft')}}
</style></head><body>
<h1>Pip &amp; Blade: every picture (${Object.keys(manifest).length})</h1>
<p>Generated by code (tools/artgen, <code>npm run art</code>). Each picture on light and on dark. Icons are one colour and are tinted by the game.</p>
${sections}
</body></html>
`;
}

/** `icons` false for a --staged review build: the PNG app icons are left as they are. */
export async function finishBuild(root: string, manifest: Record<string, SpriteInfo>, icons: boolean): Promise<void> {
  writeFileSync(join(root, 'public', 'gallery.html'), galleryHtml(manifest));
  if (icons && manifest['app.icon']) await writeAppIcons(root);
}
