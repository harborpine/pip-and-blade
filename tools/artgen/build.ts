/**
 * Full build: every 0.3.0 asset as public/art/<id>.svg, the manifest, the palette exports,
 * the app icons and the gallery.
 */
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ASSET_LIST } from '../../src/shared/assets';
import type { SpriteInfo } from '../../src/shared/assets';
import { drawAsset } from './registry';
import { BASE, EXTRA, HERO_COLOR, PALETTE } from './palette';

/** The 0.3.0 asset ids: ASSET_LIST minus what flat-style.md section 9 removes. */
export function flatAssetIds(): string[] {
  const keepDie = new Set(['die.jammed', 'die.cursed']);
  return ASSET_LIST.filter((a) => a.category !== 'kit' && (a.category !== 'die' || keepDie.has(a.id))).map((a) => a.id);
}

export function paletteCss(): string {
  const lines = [
    ...Object.entries({ ...BASE, ...EXTRA }).map(([k, v]) => `  --c-${k}: ${v};`),
    ...Object.entries(HERO_COLOR).map(([k, v]) => `  --hero-${k}: ${v};`),
  ];
  return `/* Generated by tools/artgen (npm run art). The 0.3.0 palette (docs/flat-style.md section 2). */\n:root {\n${lines.join('\n')}\n}\n`;
}

export interface BuildResult { written: string[]; missing: string[]; manifest: Record<string, SpriteInfo> }

export interface BuildOptions {
  root: string;
  /** Manifest file name in src/art/generated (manifest-flat.json until the cut-over). */
  manifestName: string;
  /** Delete PNGs from public/art (cut-over only). */
  removePngs: boolean;
}

export function buildAll(opts: BuildOptions): BuildResult {
  const artDir = join(opts.root, 'public', 'art');
  const genDir = join(opts.root, 'src', 'art', 'generated');
  mkdirSync(artDir, { recursive: true });
  mkdirSync(genDir, { recursive: true });
  const ids = flatAssetIds();
  const sprites: Record<string, SpriteInfo> = {};
  const written: string[] = [];
  const missing: string[] = [];
  for (const id of ids) {
    const a = drawAsset(id);
    if (!a) {
      missing.push(id);
      continue;
    }
    writeFileSync(join(artDir, `${id}.svg`), a.svg);
    written.push(id);
    sprites[id] = { file: `art/${id}.svg`, w: a.w, h: a.h, ax: a.w / 2, ay: a.h / 2, render: 'flat' };
  }
  // stale SVGs (ids no longer on the list) go
  const wanted = new Set(written.map((id) => `${id}.svg`));
  for (const f of readdirSync(artDir)) {
    if (f.endsWith('.svg') && !wanted.has(f)) rmSync(join(artDir, f));
    if (opts.removePngs && f.endsWith('.png')) rmSync(join(artDir, f));
  }
  const manifest = { generatedBy: 'artgen', palette: Object.values(PALETTE), sprites };
  writeFileSync(join(genDir, opts.manifestName), `${JSON.stringify(manifest, null, 1)}\n`);
  writeFileSync(join(genDir, 'palette.css'), paletteCss());
  writeFileSync(join(genDir, 'colors.json'), `${JSON.stringify({ palette: PALETTE, hero: HERO_COLOR }, null, 1)}\n`);
  if (!existsSync(join(genDir, opts.manifestName))) throw new Error('manifest not written');
  return { written, missing, manifest: sprites };
}
